    /** Emoji whose keywords contain every word of [query] (case-insensitive). */
    fun search(query: String): List<EmojiEntry> {
        val words = query.lowercase().split(' ').filter { it.isNotBlank() }
        if (words.isEmpty()) return emptyList()
        return categories.values.flatten().filter { entry -> words.all { word -> entry.keywords.split(' ').any { it.startsWith(word) } } }
    }
